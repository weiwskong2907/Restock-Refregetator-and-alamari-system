/**
 * Smartly maps a semantic role (e.g. 'freezer-main', 'fridge-upper')
 * to the best matching compartment ID in the chosen fridge model.
 */
export function remapCompartmentForModel(
  preferredRole: SemanticZoneRole,
  targetModel: FridgeModelType,
): CompartmentId {
  const preset = FRIDGE_MODEL_MAP[targetModel];
  const exact = preset.compartments.find((c) => c.role === preferredRole);
  if (exact) return exact.id;

  const fallbackOrder: Record<SemanticZoneRole, SemanticZoneRole[]> = {
    'freezer-main': ['freezer-drawer', 'fridge-upper', 'fridge-middle'],
    'freezer-drawer': ['freezer-main', 'fridge-lower', 'fridge-middle'],
    'fridge-upper': ['fridge-middle', 'fridge-lower', 'fridge-door'],
    'fridge-middle': ['fridge-upper', 'fridge-lower', 'fridge-door'],
    'fridge-lower': ['fridge-middle', 'fridge-upper', 'fridge-door'],
    'fridge-door': ['fridge-middle', 'fridge-upper', 'fridge-lower'],
    'cabinet-top': ['fridge-upper'],
    'cabinet-middle': ['fridge-middle'],
    'cabinet-bottom': ['fridge-lower'],
    'cabinet-drawer': ['fridge-door'],
  };

  for (const candidate of fallbackOrder[preferredRole] ?? []) {
    const match = preset.compartments.find((c) => c.role === candidate);
    if (match) return match.id;
  }

  return preset.compartments[0].id;
}
